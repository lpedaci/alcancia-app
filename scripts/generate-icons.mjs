const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('@material-symbols/svg-300/package.json'));
const root = dirname(dirname(fileURLToPath(import.meta.url)));

function readPath(file) {
  const svg = readFileSync(join(pkgDir, 'rounded', file), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (viewBox !== '0 -960 960 960' || paths.length !== 1) {
    throw new Error(`Unexpected SVG structure in ${file}`);
  }
  return paths[0];
}

const unique = [...new Set(ICONS)].sort();
const entries = unique.map((name) => {
  const outline = readPath(`${name}.svg`);
  let fill;
  try {
    fill = readPath(`${name}-fill.svg`);
  } catch {
    fill = outline;
  }
  return `  ${JSON.stringify(name)}: { outline: ${JSON.stringify(outline)}, fill: ${JSON.stringify(fill)} },`;
});

const out = `// AUTO-GENERATED by scripts/generate-icons.mjs. Do not edit by hand.
// Material Symbols Rounded, weight 300 (Apache-2.0, Google). viewBox: 0 -960 960 960.
export const ICON_VIEWBOX = '0 -960 960 960';

export const iconPaths = {
${entries.join('\n')}
} as const;

export type IconName = keyof typeof iconPaths;
`;

