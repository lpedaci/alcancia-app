/**
 * Economic engine of the practice wallet (docs/wallet-engine.md). Pure and deterministic: the same
 * state and actions always give the same result, so tests are reproducible and the demo states of
 * Mariana and Diego are generated by these rules, never written by hand (section 12).
 */
export const DAYS_IN_MONTH = 30;

/** Zero-based simulated month of a day: month k goes from day 30k + 1 to 30(k + 1). Day 0 is -1. */
export const monthOf = (day: number) => (day <= 0 ? -1 : Math.floor((day - 1) / DAYS_IN_MONTH));
/** Day of the simulated month, 1 to 30. */
export const dayOfMonth = (day: number) => ((day - 1) % DAYS_IN_MONTH) + 1;

export function scenarioOf(state: Pick<WalletState, 'scenarioId'>) {
  return scenarios.find((s) => s.id === state.scenarioId) ?? scenarios[1]!;
}

const sum = (values: Decimal[]) => values.reduce((total, v) => total.plus(v), ZERO);

export function pocketsTotal(state: Pick<WalletState, 'pockets'>): Decimal {
  return sum(state.pockets.map((p) => D(p.amount)));
}

export function createWallet(personId: string, scenarioId: WalletState['scenarioId'] = 'medium'): WalletState {
  return {
    version: 1,
    personId,
    day: 0,
    scenarioId,
    balance: '0.00',
    pockets: [],
    movements: [],
    yieldMode: 'none',
    salary: SALARY_START,
    expenses: { ...EXPENSES_START },
    subscriptionActive: false,
    monthSummaries: [],
    completedMissionIds: [],
    securitySettings: { twoFactor: false },
    seq: 0,
  };
}

export function addMovement(
  state: WalletState,
  movement: Omit<WalletMovement, 'id' | 'day' | 'amount'> & { amount: Decimal },
): WalletMovement {
  state.seq += 1;
  const created: WalletMovement = { ...movement, id: `m-${state.seq}`, day: state.day, amount: toMoneyString(movement.amount) };
  state.movements.push(created);
  state.balance = toMoneyString(D(state.balance).plus(movement.amount));
  return created;
}

/** Prices of each simulated month (section 5): monthly by inflation, rent every 3 months, the subscription fixed. */
function updatePrices(state: WalletState, month: number) {
  const inflation = D(scenarioOf(state).monthlyInflation);
  const quarter = ONE.plus(inflation).pow(3);
  const next: ExpenseAmounts = { ...state.expenses };
  for (const def of EXPENSE_DEFS) {
    if (def.update === 'monthly') next[def.key] = toMoneyString(D(state.expenses[def.key]).times(ONE.plus(inflation)));
    if (def.update === 'quarterly' && month % 3 === 0) next[def.key] = toMoneyString(D(state.expenses[def.key]).times(quarter));
  }
  state.expenses = next;
  // D-111: the salary follows the accumulated inflation of each quarter, like a sample wage agreement.
  if (month % 3 === 0) state.salary = toMoneyString(D(state.salary).times(quarter));
}

/** Equal parts of a monthly expense; the last part takes the cents left so the month adds up. */
function partOf(total: string, parts: number, index: number): Decimal {
  const each = roundCents(D(total).div(parts));
  return index < parts - 1 ? each : D(total).minus(each.times(parts - 1));
}

/** Money that leaves for spending: scheduled debits and the person's own payments (not pockets). */
const SPENDING: MovementType[] = ['transfer_out', 'qr_payment', 'bill', 'loan', 'card_payment', 'installment'];

export interface MonthBreakdown {
  month: number;
  income: Decimal;
  needs: Decimal;
  wants: Decimal;
  /** Payments without a category yet (the person's own transfers before she categorizes them). */
  unclassified: Decimal;
  saved: Decimal;
  yield: Decimal;
  savingsWithdrawn: boolean;
  /** The three conditions of a green month (section 8, D-115). */
  checks: { withinIncome: boolean; savedTenPercent: boolean; savingsKept: boolean };
  green: boolean;
}

/**
 * Budget of one simulated month, closed or in progress (section 8, P4): income, spending by
 * category (the person's category first, then the suggested one), money set aside and yield.
 */
export function monthBreakdown(state: WalletState, month: number): MonthBreakdown {
  const from = month * DAYS_IN_MONTH + 1;
  const to = (month + 1) * DAYS_IN_MONTH;
  const inMonth = state.movements.filter((m) => m.day >= from && m.day <= to);
  const income = sum(inMonth.filter((m) => m.type === 'income' || m.type === 'transfer_in').map((m) => D(m.amount)));
  const spending = inMonth.filter((m) => SPENDING.includes(m.type) && D(m.amount).lt(0));
  const byCategory = (category: BudgetCategory | undefined) =>
    sum(spending.filter((m) => (m.category ?? m.suggestedCategory) === category).map((m) => D(m.amount).neg()));
  const needs = byCategory('needs');
  const wants = byCategory('wants');
  const unclassified = byCategory(undefined);
  // Pockets and practice fixed-term deposits are money set aside, not spending (section 8).
  const saved = sum(inMonth.filter((m) => m.type === 'pocket_in' || m.type === 'pocket_out' || m.type === 'term_deposit' || m.type === 'brokerage').map((m) => D(m.amount).neg()));
  const yieldTotal = sum(inMonth.filter((m) => m.type === 'yield').map((m) => D(m.amount)));
  const savingsWithdrawn = inMonth.some((m) => m.type === 'pocket_out');
  // Section 8 (D-115): spending within income, at least 10 % set aside, and no savings taken out.
  const checks = {
    withinIncome: needs.plus(wants).plus(unclassified).lte(income),
    savedTenPercent: income.gt(0) && saved.gte(income.times('0.1')),
    savingsKept: !savingsWithdrawn,
  };
  return {
    month,
    income,
    needs,
    wants,
    unclassified,
    saved,
    yield: yieldTotal,
    savingsWithdrawn,
    checks,
    green: checks.withinIncome && checks.savedTenPercent && checks.savingsKept,
  };
}

function closeMonth(state: WalletState, month: number) {
  const b = monthBreakdown(state, month);
  const summary: MonthSummary = {
    month,
    income: toMoneyString(b.income),
    needs: toMoneyString(b.needs),
    // Payments the person did not categorize count as wants until she does (conservative).
    wants: toMoneyString(b.wants.plus(b.unclassified)),
    saved: toMoneyString(b.saved),
    yield: toMoneyString(b.yield),
    savingsWithdrawn: b.savingsWithdrawn,
    green: b.green,
  };
  state.monthSummaries = [...state.monthSummaries.filter((s) => s.month !== month), summary];
}

const MM_FACTORS = moneyMarketSeries.dailyFactors;
/** Daily factor of the practice money market fund on a day (section 6): it varies, it is not guaranteed. */
export const moneyMarketFactor = (day: number) => D(MM_FACTORS[((day % MM_FACTORS.length) + MM_FACTORS.length) % MM_FACTORS.length]!);

/** Example TNA of a yield mode in the scenario; the fund's one of a given day includes its daily factor. */
export function tnaOf(state: Pick<WalletState, 'scenarioId'>, mode: YieldMode, day?: number): string | null {
  const rates = scenarioOf(state).exampleRates;
  if (mode === 'remunerated') return rates.remunerated;
  if (mode === 'money_market') return day === undefined ? rates.moneyMarket : D(rates.moneyMarket).times(moneyMarketFactor(day)).toString();
  return null;
}

/**
 * Processes the next simulated day. Order (section 2, D-158): yield of the day, new month (prices
 * and salary, credited first thing in the morning), scheduled debits, month close. Stops at a debit
 * that cannot be charged: the balance never goes negative.
 */
function processDay(state: WalletState): boolean {
  state.day += 1;
  const day = state.day;
  const month = monthOf(day);
  const dom = dayOfMonth(day);

  const tna = tnaOf(state, state.yieldMode, day);
  if (tna) {
    const base = D(state.balance).plus(pocketsTotal(state));
    const credit = dailyYield(base, tna);
    if (credit.gt(0)) {
      addMovement(state, {
        type: 'yield',
        amount: credit,
        counterparty: state.yieldMode === 'remunerated' ? 'Rendimiento de la cuenta remunerada' : 'Rendimiento del fondo de práctica',
      });
    }
  }

  if (dom === 1) {
    if (month > 0) updatePrices(state, month);
    addMovement(state, { type: 'income', amount: D(state.salary), counterparty: EMPLOYER, suggestedCategory: undefined });
  }

  closeDueStatement(state);
  payOutDeposits(state);
  if (!chargeDebits(state, debitsOf(state, dom))) return false;

  if (dom === DAYS_IN_MONTH) closeMonth(state, month);
  return true;
}

interface Debit {
  /** `expense:<key>` or `plan:<id>`, to resume from it when it could not be charged. */
  id: string;
  type: MovementType;
  amount: Decimal;
  counterparty: string;
  expenseKey?: ExpenseKey;
  planId?: string;
  category?: BudgetCategory;
}

/** Scheduled debits of a day of the month, in order: the profile's expenses, then installments. */
function debitsOf(state: WalletState, dom: number): Debit[] {
  const debits: Debit[] = [];
  for (const def of EXPENSE_DEFS) {
    const index = def.days.indexOf(dom);
    if (index === -1) continue;
    if (def.key === 'subscription' && !state.subscriptionActive) continue;
    debits.push({
      id: `expense:${def.key}`,
      type: def.type,
      amount: partOf(state.expenses[def.key], def.days.length, index),
      counterparty: def.counterparty,
      expenseKey: def.key,
      category: def.category,
    });
  }
  for (const plan of state.plans ?? []) {
    if (plan.closed || plan.paid >= plan.count || plan.dayOfMonth !== dom || state.day <= plan.startDay) continue;
    debits.push({
      id: `plan:${plan.id}`,
      type: plan.kind === 'loan' ? 'loan' : 'installment',
      amount: D(plan.installment),
      counterparty: `${plan.counterparty} · cuota ${plan.paid + 1} de ${plan.count}`,
      planId: plan.id,
      category: plan.kind === 'loan' ? 'needs' : 'wants',
    });
  }
  return debits;
}

/** Charges debits in order; stops at the first one the balance cannot cover (it never goes negative). */
function chargeDebits(state: WalletState, debits: Debit[]): boolean {
  for (const debit of debits) {
    if (D(state.balance).lt(debit.amount)) {
      state.pendingDebit = {
        expenseKey: debit.expenseKey,
        planId: debit.planId,
        counterparty: debit.counterparty,
        amount: toMoneyString(debit.amount),
        day: state.day,
      };
      return false;
    }
    addMovement(state, {
      type: debit.type,
      amount: debit.amount.neg(),
      counterparty: debit.counterparty,
      expenseKey: debit.expenseKey,
      suggestedCategory: debit.category,
    });
    if (debit.planId) {
      const plan = state.plans?.find((p) => p.id === debit.planId);
      if (plan) plan.paid += 1;
    }
  }
  return true;
}

/**
 * A pending debit is charged as soon as the balance covers it (for example, after taking money out
 * of a pocket), together with the rest of that day's debits and the month close if it was day 30.
 */
function resumePending(state: WalletState): boolean {
  const pending = state.pendingDebit;
  if (!pending) return true;
  if (D(state.balance).lt(pending.amount)) return false;
  const dom = dayOfMonth(pending.day);
  const debits = debitsOf(state, dom);
  const id = pending.planId ? `plan:${pending.planId}` : `expense:${pending.expenseKey}`;
  const from = Math.max(0, debits.findIndex((d) => d.id === id));
  state.pendingDebit = undefined;
  if (!chargeDebits(state, debits.slice(from))) return false;
  if (dom === DAYS_IN_MONTH) closeMonth(state, monthOf(pending.day));
  return true;
}

export const clone = (state: WalletState): WalletState => structuredClone(state);

/** "Avanzar un día / una semana" and replays: processes n days, stopping at a pending debit. */
export function advanceDays(state: WalletState, days: number): WalletState {
  const next = clone(state);
  if (!resumePending(next)) return next;
  for (let i = 0; i < days; i += 1) if (!processDay(next)) break;
  return next;
}

/** Charges a pending debit now, if the balance covers it, without moving the day. */
export function retryPendingDebit(state: WalletState): WalletState {
  const next = clone(state);
  resumePending(next);
  return next;
}

/** "Avanzar un mes": up to the last day of the simulated month in progress (section 2). */
export function advanceMonth(state: WalletState): WalletState {
  const remaining = state.day <= 0 ? DAYS_IN_MONTH : DAYS_IN_MONTH - dayOfMonth(state.day) || DAYS_IN_MONTH;
  return advanceDays(state, remaining);
}

