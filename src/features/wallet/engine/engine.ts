export const CATEGORIZABLE: MovementType[] = ['transfer_out', 'qr_payment', 'bill'];

/** Essential monthly expenses (section 7): needs of the last closed month, or the profile at today's prices. */
export function essentialMonthlyExpenses(state: WalletState): Decimal {
  const last = [...state.monthSummaries].sort((a, b) => b.month - a.month)[0];
  if (last) return D(last.needs);
  return sum(EXPENSE_DEFS.filter((d) => d.category === 'needs').map((d) => D(state.expenses[d.key])));
}

export function emergencyFund(state: WalletState): Pocket | undefined {
  return state.pockets.find((p) => p.isEmergencyFund);
}

export function walletMetrics(state: WalletState): WalletMetrics {
  const fund = emergencyFund(state);
  return {
    categorized_movements: state.movements.filter((m) => m.category && CATEGORIZABLE.includes(m.type)).length,
    months_closed_green: state.monthSummaries.filter((s) => s.green).length,
    emergency_pocket: fund ? 1 : 0,
    emergency_months: fund ? emergencyMonths(fund.amount, essentialMonthlyExpenses(state)).toFixed(1) : '0.0',
    high_rate_debt: activeDebts(state).filter((d) => d.highRate).length,
  };
}

/** Purchasing power of the available balance today: balance ÷ (1 + π)^(day / 30) (F-26). */
export function purchasingPowerToday(state: WalletState): Decimal {
  const inflation = D(scenarioOf(state).monthlyInflation);
  return D(state.balance).div(ONE.plus(inflation).pow(D(state.day).div(DAYS_IN_MONTH)));
}

