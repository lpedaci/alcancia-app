export function createPocket(state: WalletState, pocket: Omit<Pocket, 'amount'>): WalletState {
  const next = clone(state);
  if (next.pockets.some((p) => p.id === pocket.id)) return next;
  if (pocket.isEmergencyFund) next.pockets = next.pockets.map((p) => ({ ...p, isEmergencyFund: false }));
  next.pockets.push({ ...pocket, amount: '0.00' });
  return next;
}

export function markEmergencyFund(state: WalletState, pocketId: string, goal?: string): WalletState {
  const next = clone(state);
  next.pockets = next.pockets.map((p) =>
    p.id === pocketId ? { ...p, isEmergencyFund: true, goal: goal ?? p.goal } : { ...p, isEmergencyFund: false },
  );
  return next;
}

export class WalletError extends Error {}

/** Moves money from the available balance into a pocket (a pocket is part of the same account). */
export function moveToPocket(state: WalletState, pocketId: string, amount: string): WalletState {
  const value = roundCents(amount);
  if (value.lte(0)) throw new WalletError('amount_not_positive');
  if (D(state.balance).lt(value)) throw new WalletError('insufficient_balance');
  const next = clone(state);
  const pocket = next.pockets.find((p) => p.id === pocketId);
  if (!pocket) throw new WalletError('unknown_pocket');
  pocket.amount = toMoneyString(D(pocket.amount).plus(value));
  addMovement(next, { type: 'pocket_in', amount: value.neg(), counterparty: `Apartado: ${pocket.name}`, suggestedCategory: 'savings' });
  return next;
}

export function withdrawFromPocket(state: WalletState, pocketId: string, amount: string): WalletState {
  const value = roundCents(amount);
  const next = clone(state);
  const pocket = next.pockets.find((p) => p.id === pocketId);
  if (!pocket) throw new WalletError('unknown_pocket');
  if (value.lte(0) || D(pocket.amount).lt(value)) throw new WalletError('insufficient_pocket');
  pocket.amount = toMoneyString(D(pocket.amount).minus(value));
  addMovement(next, { type: 'pocket_out', amount: value, counterparty: `Apartado: ${pocket.name}` });
  return next;
}

/** The person confirms or changes the category of a movement (D-114). */
export function categorize(state: WalletState, movementId: string, category: BudgetCategory): WalletState {
  const next = clone(state);
  const movement = next.movements.find((m) => m.id === movementId);
  if (movement) movement.category = category;
  return next;
}

export function setYieldMode(state: WalletState, mode: YieldMode): WalletState {
  return { ...clone(state), yieldMode: mode };
}

/**
 * Mission 1 surprise (D-55): a fictitious subscription is debited without warning today and keeps
 * being debited on day 1 of each month until it is cancelled.
 */
export function chargeSurpriseSubscription(state: WalletState): WalletState {
  const next = clone(state);
  const def = EXPENSE_DEFS.find((d) => d.key === 'subscription')!;
  const amount = D(next.expenses.subscription);
  if (D(next.balance).lt(amount)) throw new WalletError('insufficient_balance');
  addMovement(next, { type: def.type, amount: amount.neg(), counterparty: def.counterparty, expenseKey: 'subscription', suggestedCategory: 'wants' });
  next.subscriptionActive = true;
  return next;
}

export function setSubscription(state: WalletState, active: boolean): WalletState {
  return { ...clone(state), subscriptionActive: active };
}

export function completeMission(state: WalletState, missionId: string): WalletState {
  const next = clone(state);
  if (!next.completedMissionIds.includes(missionId)) next.completedMissionIds.push(missionId);
  return next;
}

export function setTwoFactor(state: WalletState, on: boolean): WalletState {
  const next = clone(state);
  next.securitySettings = { ...next.securitySettings, twoFactor: on };
  return next;
}

/** Daily transfer limit of practice (mission "Configura tu seguridad", 5.3 Seguridad). */
export function setDailyLimit(state: WalletState, amount: string | undefined): WalletState {
  const next = clone(state);
  next.securitySettings = { ...next.securitySettings, dailyLimit: amount === undefined ? undefined : toMoneyString(roundCents(amount)) };
  return next;
}

